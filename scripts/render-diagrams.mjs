/**
 * Renders the Mermaid diagrams of docs/ARCHITECTURE.md into docs/diagrams/: for every diagram a
 * Mermaid source (`.mmd`), a vector image (`.svg`) and a bitmap (`.png`, 2×), plus an index
 * (`README.md`). ARCHITECTURE.md stays the source of truth — edit a diagram there, then rerun.
 *
 * Usage: node scripts/render-diagrams.mjs --mermaid <path to mermaid/dist/mermaid.min.js>
 *
 * Mermaid is deliberately not a project dependency: install it once in any folder outside the
 * project (`npm install mermaid@11`) and pass its browser bundle. Rendering runs locally in
 * Playwright's bundled Chromium (the project's E2E browser) and makes no network requests.
 */
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import { chromium } from "@playwright/test";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = path.join(ROOT, "docs", "ARCHITECTURE.md");
const OUT_DIR = path.join(ROOT, "docs", "diagrams");
const GENERATED_FILE = /^\d{2}-[a-z0-9-]+\.(?:mmd|svg|png)$/;

/** File name and title of every diagram, in the order the blocks appear in ARCHITECTURE.md. */
const DIAGRAMS = [
  ["01-system-overview", "System overview"],
  ["02-module-dependencies", "Module dependencies"],
  ["03-request-routing", "Request routing"],
  ["04-data-model", "Data model"],
  ["05-auth-support-tables", "Standalone auth tables"],
  ["06-sign-in-flow", "Sign-in and session check"],
  ["07-editor-architecture", "Editor architecture"],
  ["08-interaction-states", "Editor interaction states"],
  ["09-model-import", "Importing your own model"],
  ["10-cloud-autosave", "Cloud autosave and conflicts"],
  ["11-deployment", "Build and deployment"],
];

const MERMAID_CONFIG = {
  startOnLoad: false,
  theme: "default",
  securityLevel: "strict",
  flowchart: { useMaxWidth: false, htmlLabels: true },
  sequence: { useMaxWidth: false },
  er: { useMaxWidth: false },
  state: { useMaxWidth: false },
};

function readMermaidBundle(argv) {
  const index = argv.indexOf("--mermaid");
  const bundle = index >= 0 ? argv[index + 1] : undefined;
  if (!bundle) {
    console.error("Usage: node scripts/render-diagrams.mjs --mermaid <path to mermaid.min.js>");
    process.exit(2);
  }
  return path.resolve(bundle);
}

/** Every ```mermaid block of the document with the nearest heading above it. */
function extractDiagrams(markdown) {
  const lines = markdown.split("\n");
  const diagrams = [];
  let heading = "";
  for (let i = 0; i < lines.length; i++) {
    if (/^#{2,3} /.test(lines[i])) heading = lines[i].replace(/^#+ /, "");
    if (lines[i] !== "```mermaid") continue;
    const end = lines.indexOf("```", i + 1);
    if (end < 0) throw new Error(`Unclosed mermaid block at line ${i + 1}`);
    diagrams.push({ heading, source: lines.slice(i + 1, end).join("\n") + "\n" });
    i = end;
  }
  return diagrams;
}

/** GitHub's heading anchor: lower case, punctuation removed, spaces become hyphens. */
function githubAnchor(heading) {
  return heading
    .trim()
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\- _]/gu, "")
    .replace(/ /g, "-");
}

/** Heading without status notes (`*(implemented)*`) and trailing code paths. */
function sectionTitle(heading) {
  return heading
    .replace(/\s*\*\(.*?\)\*/g, "")
    .replace(/\s+—\s+`.*$/, "")
    .trim();
}

function indexMarkdown(entries) {
  const rows = entries.map(
    ({ name, title, heading }) =>
      `| ${name.slice(0, 2)} | ${title} | [${sectionTitle(heading)}](../ARCHITECTURE.md#${githubAnchor(heading)}) | ` +
      `[PNG](${name}.png) · [SVG](${name}.svg) · [Mermaid](${name}.mmd) |`,
  );
  const sections = entries.map(
    ({ name, title }) => `## ${name.slice(0, 2)} · ${title}\n\n![${title}](${name}.png)\n`,
  );
  return [
    "# Architecture diagrams",
    "",
    "<!-- Generated by scripts/render-diagrams.mjs from docs/ARCHITECTURE.md. Do not edit by hand. -->",
    "",
    "Rendered copies of the Mermaid diagrams in [ARCHITECTURE.md](../ARCHITECTURE.md), which stays the",
    "source of truth (GitHub also renders those diagrams inline). Each diagram has its Mermaid source",
    "(`.mmd`), a vector image (`.svg`) and a bitmap (`.png`).",
    "",
    "| # | Diagram | Section in ARCHITECTURE.md | Files |",
    "|---|---|---|---|",
    ...rows,
    "",
    "To update the files, edit the diagram in ARCHITECTURE.md, then run the generator. Mermaid is not a",
    "project dependency, so install it once in any folder outside the project:",
    "",
    "```powershell",
    "npm install mermaid@11   # in a scratch folder",
    "node scripts/render-diagrams.mjs --mermaid <scratch folder>/node_modules/mermaid/dist/mermaid.min.js",
    "```",
    "",
    ...sections,
  ].join("\n");
}

async function main() {
  const bundle = readMermaidBundle(process.argv.slice(2));
  const diagrams = extractDiagrams(readFileSync(SOURCE, "utf8").replace(/\r\n/g, "\n"));
  if (diagrams.length !== DIAGRAMS.length) {
    throw new Error(
      `ARCHITECTURE.md has ${diagrams.length} Mermaid diagrams but DIAGRAMS lists ${DIAGRAMS.length} — update the list.`,
    );
  }
  const entries = diagrams.map((diagram, i) => ({
    ...diagram,
    name: DIAGRAMS[i][0],
    title: DIAGRAMS[i][1],
  }));

  mkdirSync(OUT_DIR, { recursive: true });
  for (const file of readdirSync(OUT_DIR)) {
    if (GENERATED_FILE.test(file)) rmSync(path.join(OUT_DIR, file));
  }

  const browser = await chromium.launch();
  try {
    const page = await browser.newPage({ viewport: { width: 1600, height: 1200 }, deviceScaleFactor: 2 });
    await page.setContent(
      '<!doctype html><html><body style="margin:0;background:#fff">' +
        '<div id="host" style="display:inline-block;padding:24px;background:#fff"></div></body></html>',
    );
    await page.addScriptTag({ path: bundle });
    await page.evaluate((config) => window.mermaid.initialize(config), MERMAID_CONFIG);

    for (const { name, source } of entries) {
      const svg = await page.evaluate(
        async ({ id, text }) => {
          const { svg: markup } = await window.mermaid.render(id, text);
          const host = document.getElementById("host");
          host.innerHTML = markup;
          const element = host.querySelector("svg");
          // An opaque background keeps the diagram readable in dark viewers.
          const [x, y, width, height] = element.getAttribute("viewBox").split(/\s+/).map(Number);
          const background = document.createElementNS("http://www.w3.org/2000/svg", "rect");
          Object.entries({ x, y, width, height, fill: "#ffffff" }).forEach(([key, value]) =>
            background.setAttribute(key, String(value)),
          );
          element.insertBefore(background, element.firstChild);
          return new XMLSerializer().serializeToString(element);
        },
        { id: `diagram-${name}`, text: source },
      );
      writeFileSync(path.join(OUT_DIR, `${name}.mmd`), source);
      writeFileSync(path.join(OUT_DIR, `${name}.svg`), `${svg}\n`);
      await page.locator("#host").screenshot({ path: path.join(OUT_DIR, `${name}.png`) });
      console.log(`docs/diagrams/${name}.{mmd,svg,png}`);
    }
  } finally {
    await browser.close();
  }

  writeFileSync(path.join(OUT_DIR, "README.md"), indexMarkdown(entries));
  console.log("docs/diagrams/README.md");
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
