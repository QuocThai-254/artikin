// Writes the hero illustration SVG (brand/ + public/ for the prototype), its inline TS copy for the
// landing hero plate, its anchor points for the HTML annotation overlay, and a PNG preview (bundled
// Chromium).
import { writeFileSync, mkdirSync } from "node:fs";
import { heroScene, heroSceneSvg, BULB } from "./hero-scene.mjs";
import { rasterize } from "./raster.mjs";

mkdirSync("brand", { recursive: true });
mkdirSync("public", { recursive: true });
mkdirSync("src/landing", { recursive: true });
mkdirSync("out", { recursive: true });
// Web hero: no SVG filters (they dominate main-thread rendering cost on phones; Lighthouse LCP/TBT).
const opts = { gizmo: false, viewBox: [-840, -520, 1680, 1680], filters: false };
const svg = heroSceneSvg(opts);
writeFileSync("brand/hero-mannequin.svg", svg);
writeFileSync("public/hero-mannequin.svg", svg);

// Inline copy for the landing hero plate: it paints with the first frame (no request, and inline SVG
// shapes are not LCP candidates). The plate's wrapper carries role="img" and the accessible name, so
// the inner SVG is hidden from assistive tech and drops its <title> (it would show as a tooltip).
const inline = svg
  .replace(/<title>[^<]*<\/title>/, "")
  .replace(
    / role="img" aria-label="[^"]*"/,
    ' width="100%" height="100%" aria-hidden="true" focusable="false"',
  );
if (!inline.includes('aria-hidden="true"') || /[`\\]|\$\{/.test(inline)) {
  throw new Error(
    "hero SVG: unexpected root element or characters that cannot go in a template literal",
  );
}
writeFileSync(
  "src/landing/hero-svg.ts",
  "// Generated by docs/brand/generator/scripts/build-hero.mjs — do not edit by hand.\n" +
    "// Inline copy of public/brand/hero-mannequin.svg for the landing hero plate.\n" +
    `export const HERO_SVG = \`${inline}\`;\n`,
);

const { anchors, viewBox } = heroScene(opts);
const round = (p) => p.map((v) => Math.round(v * 10) / 10);
const data = {
  viewBox,
  bulb: BULB,
  shoulder: round(anchors.leftShoulder),
  elbow: round(anchors.leftElbow),
  hand: round(anchors.leftHand),
  head: round(anchors.head),
  headTop: Math.round(anchors.head[1] - 67),
  floor: 1000,
  feet: anchors.feet.map(round),
  upperArmAngle: -148,
};
writeFileSync("src/landing/hero-anchors.json", JSON.stringify(data, null, 2));
const [png] = await rasterize([{ svg, width: 700, height: 700, transparent: false }]);
writeFileSync("out/hero-mannequin.png", png);
console.log(
  `hero-mannequin.svg ${(svg.length / 1024).toFixed(1)} KB; anchors → src/landing/hero-anchors.json`,
);
