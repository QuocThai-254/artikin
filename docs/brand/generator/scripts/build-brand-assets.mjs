// Builds every Artikin brand asset from code (no hand-exported files):
//   brand/logo/*.svg       mark (tile / glyph / mono), wordmark, lockups
//   brand/icons/*          icon.svg, favicon.ico (16/32/48), PNG 16/32/48/192/512, apple-icon (180), maskable 512
//   brand/og/*             opengraph-image.png (1200×630) + .html source + .alt.txt
//   public/brand/*         copies used by the Vite prototype
// Rasterized with the bundled Chromium (scripts/raster.mjs). Run: node scripts/build-brand-assets.mjs
import { rasterize } from "./raster.mjs";
import { mkdirSync, writeFileSync, copyFileSync, readdirSync } from "node:fs";
import path from "node:path";
import { HEX, markSvg, wordmarkSvg, lockupSvg, wordmarkGeometry, MARK } from "./brand-lib.mjs";
import { ogHtml, OG_ALT } from "./og-image.mjs";

const OUT = "brand";
for (const d of ["logo", "icons", "og"]) mkdirSync(path.join(OUT, d), { recursive: true });
mkdirSync("public/brand", { recursive: true });
mkdirSync("out", { recursive: true });

const write = (rel, data) => {
  writeFileSync(path.join(OUT, rel), data);
  return path.join(OUT, rel);
};

// ---------- logos ----------
write("logo/artikin-mark.svg", markSvg({ variant: "tile", title: "Artikin" }));
write("logo/artikin-mark-glyph.svg", markSvg({ variant: "glyph", title: "Artikin" }));
write("logo/artikin-mark-mono.svg", markSvg({ variant: "mono", title: "Artikin" }));
write("logo/artikin-wordmark.svg", wordmarkSvg({ color: HEX.foreground }).svg);
write(
  "logo/artikin-wordmark-mono.svg",
  wordmarkSvg({ color: "currentColor", dotColor: "currentColor" }).svg,
);
write("logo/artikin-lockup.svg", lockupSvg({ markVariant: "tile", color: HEX.foreground }));
write("logo/artikin-lockup-glyph.svg", lockupSvg({ markVariant: "glyph", color: HEX.foreground }));
write(
  "logo/artikin-lockup-mono.svg",
  lockupSvg({ markVariant: "mono", color: "currentColor", dotColor: "currentColor" }),
);

// ---------- icons ----------
const tile = markSvg({ variant: "tile" });
const square = markSvg({ variant: "tile-square" });
write("icons/icon.svg", markSvg({ variant: "tile", title: "Artikin" }));
const sizes = [16, 32, 48, 192, 512];
// Maskable: full-bleed background, glyph scaled into the 80 % safe zone.
const maskable = square
  .replace(/<g mask=/, `<g transform="translate(6.4 6.4) scale(.8)"><g mask=`)
  .replace(/(<circle cx="32" cy="15" r="7"[^>]*\/>)<\/svg>$/, "$1</g></svg>");
const og = ogHtml();
const raster = await rasterize([
  ...sizes.map((s) => ({ svg: tile, width: s, height: s })),
  { svg: square, width: 180, height: 180, transparent: false },
  { svg: maskable, width: 512, height: 512, transparent: false },
  { html: og, width: 1200, height: 630, transparent: false },
]);
const pngs = Object.fromEntries(sizes.map((s, i) => [s, raster[i]]));
const [applePng, maskablePng, ogPng] = raster.slice(sizes.length);
const png = (svg, w, h) =>
  rasterize([{ svg, width: w, height: h, transparent: false }]).then((r) => r[0]);
for (const s of sizes) write(`icons/icon-${s}.png`, pngs[s]);
write("icons/apple-icon.png", applePng);
write("icons/icon-maskable-512.png", maskablePng);

// favicon.ico with embedded PNGs (16, 32, 48) — supported by all current browsers.
function ico(images) {
  const header = Buffer.alloc(6);
  header.writeUInt16LE(0, 0);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(images.length, 4);
  const entries = [];
  let offset = 6 + 16 * images.length;
  for (const { size, data } of images) {
    const e = Buffer.alloc(16);
    e.writeUInt8(size >= 256 ? 0 : size, 0);
    e.writeUInt8(size >= 256 ? 0 : size, 1);
    e.writeUInt8(0, 2);
    e.writeUInt8(0, 3);
    e.writeUInt16LE(1, 4);
    e.writeUInt16LE(32, 6);
    e.writeUInt32LE(data.length, 8);
    e.writeUInt32LE(offset, 12);
    offset += data.length;
    entries.push(e);
  }
  return Buffer.concat([header, ...entries, ...images.map((i) => i.data)]);
}
write("icons/favicon.ico", ico([16, 32, 48].map((size) => ({ size, data: pngs[size] }))));

// ---------- Open Graph ----------
write("og/opengraph-image.html", og);
write("og/opengraph-image.png", ogPng);
write("og/opengraph-image.alt.txt", OG_ALT);

// ---------- copies for the prototype ----------
for (const dir of ["logo", "icons", "og"]) {
  for (const file of readdirSync(path.join(OUT, dir)))
    copyFileSync(path.join(OUT, dir, file), path.join("public/brand", file));
}

// ---------- logo geometry for React (inline SVG; no font needed at runtime) ----------
{
  const g = wordmarkGeometry({ capHeight: 100 });
  const r = (n) => Math.round(n * 100) / 100;
  const ts = `// Generated by docs/brand/generator/scripts/build-brand-assets.mjs — do not edit by hand.
// Wordmark outlines: Geist SemiBold (SIL OFL 1.1, from the \`geist\` npm package) with ball i-dots.
export const WORDMARK = {
  d: ${JSON.stringify(g.d)},
  dots: ${JSON.stringify(g.dots.map((d) => ({ cx: r(d.cx), cy: r(d.cy), r: r(d.r) })))},
  box: ${JSON.stringify({ x1: r(g.box.x1), y1: r(Math.min(g.box.y1, ...g.dots.map((d) => d.cy - d.r))), x2: r(g.box.x2), y2: r(g.box.y2) })},
  capHeight: 100,
} as const;

export const MARK_GEOMETRY = ${JSON.stringify(MARK, null, 2)} as const;

export const BRAND_HEX = ${JSON.stringify({ amber: HEX.amber, woodLight: HEX.woodLight, wood: HEX.wood, woodShadow: HEX.woodShadow, tile: "#1C1C1C" }, null, 2)} as const;
`;
  mkdirSync("src/components/brand", { recursive: true });
  writeFileSync("src/components/brand/logo-data.ts", ts);
}

